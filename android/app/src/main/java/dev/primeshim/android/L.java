    private L() {}

    static void init(Context context) {
        SharedPreferences prefs = context.getSharedPreferences("primeshim", Context.MODE_PRIVATE);
        String value = prefs.getString("language", null);
        if (value == null) {
            String system = Locale.getDefault().getLanguage();
            value = ("en".equals(system) || "fr".equals(system)) ? system : "zh";
        }
        lang = value;
    }

    static void setLanguage(Context context, String value) {
        lang = value;
        context.getSharedPreferences("primeshim", Context.MODE_PRIVATE)
                .edit().putString("language", value).apply();
    }

    static String code() { return lang; }

    static Locale locale() {
        if ("en".equals(lang)) return Locale.ENGLISH;
        if ("fr".equals(lang)) return Locale.FRENCH;
        return Locale.SIMPLIFIED_CHINESE;
    }

    static String languageName() {
        if ("en".equals(lang)) return "English";
        if ("fr".equals(lang)) return "Français";
        return "中文";
    }

    private static String clean(String value) {
        return value.replace("\\n", "\n").replace("\\t", "\t");
    }

    static String t(String zh) {
        if (zh == null) return "";
        if ("en".equals(lang)) {
            String value = EN.get(zh);
            return clean(value != null ? value : zh);
        }
        if ("fr".equals(lang)) {
            String value = FR.get(zh);
            return clean(value != null ? value : zh);
        }
        return clean(zh);
    }
